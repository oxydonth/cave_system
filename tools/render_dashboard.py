"""Generate the heating dashboard from a ``heating.yaml``.

Usage (inside the Home Assistant container, where PyYAML is installed)::

    python /cave/tools/render_dashboard.py /config/cave/.applied/heating.yaml \\
        /config/dashboards/heating.yaml

The output is a Home Assistant dashboard in YAML mode (concept section 6): a room view with
one section per room, and a maintenance view. The same input always gives the same bytes, with
the rooms in the order of the file.

The generator assumes a file that ``./cave apply`` has validated, but it still refuses a file it
cannot use with one line naming the problem, never a traceback. It reads only the keys it needs
and ignores the rest, so a newer ``heating.yaml`` with more options still renders. It does not
import the integration: the entity IDs below are the contract of concept section 5.2.

Built-in cards only. ``ALLOWED_CARD_OPTIONS`` and its companions list every card type, option,
feature and badge the generator may emit, taken from the Home Assistant 2026.10 frontend
documentation; ``check_dashboard`` verifies a dashboard against them and the generator runs it
before writing anything.
"""

import argparse
import json
import os
import re
import sys
import tempfile
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, cast

import yaml

SUPPORTED_VERSION = 1

HEADER = (
    "# Generated by tools/render_dashboard.py from the applied heating.yaml by `./cave apply`.\n"
    "# Do not edit: the next `./cave apply` overwrites this file.\n"
)

# ---------------------------------------------------------------------------------------------
# Allow-list. Home Assistant 2026.10 frontend documentation, https://www.home-assistant.io/dashboards/.
# A card type or option that is not listed here cannot be emitted; one that is listed but
# does not exist shows as an error card in the browser, so every entry was checked against the
# documentation of its card, not written from memory.
# ---------------------------------------------------------------------------------------------

_ACTION_OPTIONS = {"tap_action", "hold_action", "double_tap_action"}

ALLOWED_CARD_OPTIONS: dict[str, frozenset[str]] = {
    "entities": frozenset(
        {"type", "entities", "title", "icon", "show_header_toggle", "theme", "color"}
        | {"header", "footer"}
    ),
    "heading": frozenset({"type", "heading", "heading_style", "icon", "badges"} | {"tap_action"}),
    "history-graph": frozenset(
        {"type", "entities", "hours_to_show", "title", "show_names", "logarithmic_scale"}
        | {"min_y_axis", "max_y_axis", "fit_y_data", "expand_legend"}
    ),
    "markdown": frozenset(
        {"type", "content", "title", "card_size", "entity_id", "theme", "show_empty", "text_only"}
        | _ACTION_OPTIONS
    ),
    "thermostat": frozenset(
        {"type", "entity", "name", "theme", "show_current_as_primary", "features"}
    ),
    "tile": frozenset(
        {"type", "entity", "name", "icon", "color", "show_entity_picture", "vertical"}
        | {"hide_state", "state_content", "time_format", "features", "features_position"}
        | _ACTION_OPTIONS
        | {"icon_tap_action", "icon_hold_action", "icon_double_tap_action"}
    ),
}

ALLOWED_CARD_TYPES = frozenset(ALLOWED_CARD_OPTIONS)

# Features of tile and thermostat cards, https://www.home-assistant.io/dashboards/features/.
ALLOWED_FEATURE_OPTIONS: dict[str, frozenset[str]] = {
    "climate-hvac-modes": frozenset({"type", "style", "hvac_modes"}),
    "climate-preset-modes": frozenset({"type", "style", "preset_modes"}),
    "numeric-input": frozenset({"type", "style"}),
    "select-options": frozenset({"type", "style", "options"}),
}

# Heading badges, https://www.home-assistant.io/dashboards/heading/#heading-badges.
ALLOWED_BADGE_OPTIONS: dict[str, frozenset[str]] = {
    "entity": frozenset(
        {"type", "entity", "name", "icon", "color", "show_icon", "show_state", "state_content"}
        | _ACTION_OPTIONS
    ),
}

# Options of an entity row given as a mapping (an entities card row without a `type`).
ALLOWED_ROW_OPTIONS = frozenset({"entity", "name", "icon", "secondary_info"})

ALLOWED_VIEW_OPTIONS = frozenset({"title", "path", "icon", "type", "sections"})
ALLOWED_SECTION_OPTIONS = frozenset({"type", "cards"})

ENTITY_ID = re.compile(r"^[a-z0-9_]+\.[a-z0-9_]+$")
ROOM_ID = re.compile(r"^[a-z0-9][a-z0-9_]*$")


class DashboardError(Exception):
    """The input cannot be turned into a dashboard; the message says why, in one line."""


# ---------------------------------------------------------------------------------------------
# Reading heating.yaml
# ---------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Room:
    """What the dashboard needs to know about one room."""

    id: str
    name: str
    temperature_sensor: str | None = None
    humidity_sensor: str | None = None
    windows: tuple[str, ...] = ()
    schedule: str | None = None


@dataclass(frozen=True)
class Home:
    """What the dashboard needs to know about the home."""

    presence: tuple[str, ...] = ()
    rooms: tuple[Room, ...] = field(default_factory=tuple)


def _entity_id(value: Any, where: str) -> str:
    if not isinstance(value, str) or not ENTITY_ID.match(value):
        raise DashboardError(f"{where}: {value!r} is not an entity ID such as sensor.living_room")
    return value


def _entity_list(value: Any, where: str) -> tuple[str, ...]:
    """One entity ID or a list of them; ``None`` means none."""
    if value is None:
        return ()
    items = [value] if isinstance(value, str) else value
    if not isinstance(items, list):
        raise DashboardError(f"{where}: expected an entity ID or a list of them")
    return tuple(_entity_id(item, where) for item in items)


def _optional_entity(value: Any, where: str) -> str | None:
    return None if value is None else _entity_id(value, where)


def _parse_room(raw: Any, index: int) -> Room:
    where = f"rooms[{index}]"
    if not isinstance(raw, Mapping):
        raise DashboardError(f"{where}: expected a mapping with id and name")
    room_id = raw.get("id")
    if not isinstance(room_id, str) or not ROOM_ID.match(room_id):
        raise DashboardError(f"{where}: id {room_id!r} must be a lower-case ASCII slug")
    where = f"room {room_id}"
    name = raw.get("name")
    if not isinstance(name, str) or not name.strip():
        raise DashboardError(f"{where}: name must be a non-empty text")
    return Room(
        id=room_id,
        name=name,
        temperature_sensor=_optional_entity(
            raw.get("temperature_sensor"), f"{where}, temperature_sensor"
        ),
        humidity_sensor=_optional_entity(raw.get("humidity_sensor"), f"{where}, humidity_sensor"),
        windows=_entity_list(raw.get("windows"), f"{where}, windows"),
        schedule=_optional_entity(raw.get("schedule"), f"{where}, schedule"),
    )


def parse_home(data: Any) -> Home:
    """Read the keys the dashboard uses from a parsed ``heating.yaml``."""
    if not isinstance(data, Mapping):
        raise DashboardError("the file must be a mapping with a `rooms` list")
    version = data.get("version", SUPPORTED_VERSION)
    if version != SUPPORTED_VERSION:
        raise DashboardError(
            f"version {version!r} is not supported by this dashboard generator "
            f"(it reads version {SUPPORTED_VERSION})"
        )
    raw_rooms = data.get("rooms")
    if raw_rooms is None:
        raw_rooms = []
    if not isinstance(raw_rooms, list):
        raise DashboardError("`rooms` must be a list")
    rooms = tuple(_parse_room(raw, index) for index, raw in enumerate(raw_rooms))
    seen: set[str] = set()
    for room in rooms:
        if room.id in seen:
            raise DashboardError(f"room id {room.id} is used twice")
        seen.add(room.id)
    return Home(presence=_entity_list(data.get("presence"), "presence"), rooms=rooms)


def load_home(path: Path) -> Home:
    """Read and parse a ``heating.yaml``."""
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise DashboardError(f"{path}: no such file") from None
    except (OSError, UnicodeDecodeError) as err:
        raise DashboardError(f"{path}: cannot be read: {err}") from None
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as err:
        mark = getattr(err, "problem_mark", None)
        where = f" at line {mark.line + 1}, column {mark.column + 1}" if mark is not None else ""
        problem = getattr(err, "problem", None) or "invalid YAML"
        raise DashboardError(f"{path}: not valid YAML{where}: {problem}") from None
    try:
        return parse_home(data)
    except DashboardError as err:
        raise DashboardError(f"{path}: {err}") from None


# ---------------------------------------------------------------------------------------------
# Building the dashboard
# ---------------------------------------------------------------------------------------------

Card = dict[str, Any]


def _section(cards: list[Card]) -> dict[str, Any]:
    return {"type": "grid", "cards": cards}


def _entity_badge(entity: str) -> Card:
    return {"type": "entity", "entity": entity, "show_state": True}


def _room_section(room: Room) -> dict[str, Any]:
    prefix = f"cave_{room.id}"
    rows = [
        f"sensor.{prefix}_reason",
        f"binary_sensor.{prefix}_window_open",
        f"number.{prefix}_comfort_temperature",
        f"number.{prefix}_eco_temperature",
        f"button.{prefix}_resume_schedule",
    ]
    if room.schedule is not None:
        rows.append(room.schedule)
    rows.extend(room.windows)
    history = [f"climate.{prefix}"]
    history.extend(
        sensor for sensor in (room.temperature_sensor, room.humidity_sensor) if sensor is not None
    )
    return _section(
        [
            {
                "type": "heading",
                "heading": room.name,
                "icon": "mdi:radiator",
                "badges": [
                    _entity_badge(f"binary_sensor.{prefix}_window_open"),
                    _entity_badge(f"binary_sensor.{prefix}_problem"),
                ],
            },
            {
                "type": "thermostat",
                "entity": f"climate.{prefix}",
                "features": [
                    {"type": "climate-hvac-modes", "style": "icons"},
                    {"type": "climate-preset-modes", "style": "dropdown"},
                ],
            },
            {"type": "entities", "show_header_toggle": False, "entities": rows},
            {"type": "history-graph", "hours_to_show": 24, "entities": history},
        ]
    )


def _home_section(home: Home) -> dict[str, Any]:
    cards: list[Card] = [
        {"type": "heading", "heading": "Home", "icon": "mdi:home-thermometer"},
        {
            "type": "tile",
            "entity": "select.cave_home_mode",
            "features": [{"type": "select-options", "style": "buttons"}],
        },
        {
            "type": "tile",
            "entity": "number.cave_away_temperature",
            "features": [{"type": "numeric-input", "style": "buttons"}],
        },
        {"type": "tile", "entity": "binary_sensor.cave_home_occupied"},
    ]
    if home.presence:
        cards.append(
            {
                "type": "entities",
                "title": "Who is home",
                "show_header_toggle": False,
                "entities": list(home.presence),
            }
        )
    if not home.rooms:
        cards.append(
            {
                "type": "markdown",
                "content": (
                    "No rooms are configured yet. Describe them in `cave/heating.yaml` and run\n"
                    "`./cave apply`; this dashboard is generated again from that file.\n"
                ),
            }
        )
    return _section(cards)


# The two templates below run in Home Assistant, not here, so the generator needs no device
# names: they ask Home Assistant which sensors exist. tests/tools/templates renders both against
# a real Home Assistant.

BATTERY_TEMPLATE = """\
{% set ns = namespace(rows=[]) %}
{% for s in states.sensor
   | selectattr('attributes.device_class', 'defined')
   | selectattr('attributes.device_class', 'eq', 'battery') %}
{% if is_number(s.state) %}
{% set unit = s.attributes.unit_of_measurement | default('%', true) %}
{% set ns.rows = ns.rows + [[s.state | float(0), s.name, s.state ~ ' ' ~ unit]] %}
{% else %}
{% set ns.rows = ns.rows + [[101, s.name, s.state]] %}
{% endif %}
{% endfor %}
{% for s in states.binary_sensor
   | selectattr('attributes.device_class', 'defined')
   | selectattr('attributes.device_class', 'eq', 'battery') %}
{% set ns.rows = ns.rows + [[0 if s.state == 'on' else 102, s.name,
   'low' if s.state == 'on' else ('ok' if s.state == 'off' else s.state)]] %}
{% endfor %}
{% if ns.rows %}
{% for row in ns.rows | sort(attribute='0') -%}
- {{ row[1] }}: **{{ row[2] }}**
{% endfor %}
{% else %}
No battery sensors known to Home Assistant.
{% endif %}
"""

UNAVAILABLE_TEMPLATE = """\
{% set ns = namespace(names=[]) %}
{% for s in states | selectattr('state', 'eq', 'unavailable') %}
{% set d = device_id(s.entity_id) %}
{% if d %}
{% set own = expand(device_entities(d)) %}
{% set name = device_attr(d, 'name_by_user') or device_attr(d, 'name') %}
{% if name and name not in ns.names and own | rejectattr('state', 'eq', 'unavailable')
   | list | count == 0 %}
{% set ns.names = ns.names + [name] %}
{% endif %}
{% endif %}
{% endfor %}
{% if ns.names %}
{% for name in ns.names | sort -%}
- {{ name }}
{% endfor %}
{% else %}
All devices are available.
{% endif %}
"""


_MARKDOWN_SPECIAL = "\\*_[]<>&`~#|"


def markdown_text(text: str) -> str:
    """``text`` as plain Markdown text: whitespace folded, every formatting character escaped."""
    folded = " ".join(text.split())
    return "".join(f"\\{char}" if char in _MARKDOWN_SPECIAL else char for char in folded)


def problem_template(rooms: Sequence[Room]) -> str:
    """The template that lists the rooms that need attention, with their two attributes.

    A room whose problem sensor is off is left out, so with twenty rooms the person reads the
    one that matters. Names are escaped for Markdown here and passed as Jinja string literals.
    """
    lines = ["{% set rooms = ["]
    for room in rooms:
        entity = json.dumps(f"binary_sensor.cave_{room.id}_problem")
        name = json.dumps(markdown_text(room.name), ensure_ascii=False)
        lines.append(f"  [{entity}, {name}],")
    lines += [
        "] -%}",
        "{% set ns = namespace(shown=0) -%}",
        "{% for entity, name in rooms -%}",
        "{% set s = states(entity) -%}",
        "{% if s != 'off' -%}",
        "{% set ns.shown = ns.shown + 1 -%}",
        "{% if s == 'on' -%}",
        "**{{ name }}**: needs attention",
        "{% for message in state_attr(entity, 'messages') or [] -%}",
        "- {{ message }}",
        "{% endfor -%}",
        "{% for thermostat, status in (state_attr(entity, 'thermostats') or {}).items() -%}",
        "- {{ thermostat }}: {{ status }}",
        "{% endfor -%}",
        "{% else -%}",
        "**{{ name }}**: {{ s }}",
        "{% endif -%}",
        # A blank line ends the room's list; without it Markdown reads the next room's name as
        # a continuation of the last bullet.
        '{{ "\\n" }}{% endif -%}',
        "{% endfor -%}",
        "{% if ns.shown == 0 -%}",
        "All rooms are ok.",
        "{% endif -%}",
    ]
    return "\n".join(lines) + "\n"


def _maintenance_view(home: Home) -> dict[str, Any]:
    problems: list[Card] = [
        {"type": "heading", "heading": "Rooms needing attention", "icon": "mdi:alert-circle"},
    ]
    if home.rooms:
        problems.append(
            {
                "type": "markdown",
                "content": problem_template(home.rooms),
                "entity_id": [f"binary_sensor.cave_{room.id}_problem" for room in home.rooms],
            }
        )
    else:
        problems.append({"type": "markdown", "content": "No rooms are configured yet.\n"})
    return {
        "title": "Maintenance",
        "path": "maintenance",
        "icon": "mdi:wrench",
        "type": "sections",
        "sections": [
            _section(
                [
                    {"type": "heading", "heading": "Batteries", "icon": "mdi:battery-heart"},
                    {"type": "markdown", "content": BATTERY_TEMPLATE},
                ]
            ),
            _section(
                [
                    {
                        "type": "heading",
                        "heading": "Unavailable devices",
                        "icon": "mdi:lan-disconnect",
                    },
                    {"type": "markdown", "content": UNAVAILABLE_TEMPLATE},
                ]
            ),
            _section(problems),
        ],
    }


def build_dashboard(home: Home) -> dict[str, Any]:
    """The dashboard for a home, as plain data."""
    dashboard: dict[str, Any] = {
        "title": "Heating",
        "views": [
            {
                "title": "Rooms",
                "path": "rooms",
                "icon": "mdi:radiator",
                "type": "sections",
                "sections": [_home_section(home), *(_room_section(room) for room in home.rooms)],
            },
            _maintenance_view(home),
        ],
    }
    problems = check_dashboard(dashboard)
    if problems:
        raise DashboardError(
            "the generator produced a card that is not allowed: " + "; ".join(problems)
        )
    return dashboard


# ---------------------------------------------------------------------------------------------
# The allow-list check
# ---------------------------------------------------------------------------------------------


def _check_options(
    kind: str, where: str, item: Mapping[str, Any], allowed: frozenset[str]
) -> list[str]:
    return [f"{where}: {kind} option `{key}` is not allowed" for key in item if key not in allowed]


def _check_features(where: str, card: Mapping[str, Any]) -> list[str]:
    problems: list[str] = []
    for index, feature in enumerate(card.get("features", [])):
        here = f"{where}.features[{index}]"
        allowed = ALLOWED_FEATURE_OPTIONS.get(feature.get("type", ""))
        if allowed is None:
            problems.append(f"{here}: feature type `{feature.get('type')}` is not allowed")
        else:
            problems.extend(_check_options("feature", here, feature, allowed))
    return problems


def _check_card(where: str, card: Any) -> list[str]:
    if not isinstance(card, Mapping):
        return [f"{where}: a card must be a mapping"]
    card_type = card.get("type")
    allowed = ALLOWED_CARD_OPTIONS.get(card_type) if isinstance(card_type, str) else None
    if allowed is None:
        return [f"{where}: card type `{card_type}` is not allowed"]
    problems = _check_options("card", where, card, allowed)
    problems.extend(_check_features(where, card))
    for index, badge in enumerate(card.get("badges", [])):
        here = f"{where}.badges[{index}]"
        allowed_badge = ALLOWED_BADGE_OPTIONS.get(badge.get("type", ""))
        if allowed_badge is None:
            problems.append(f"{here}: badge type `{badge.get('type')}` is not allowed")
        else:
            problems.extend(_check_options("badge", here, badge, allowed_badge))
    if card_type == "entities":
        for index, row in enumerate(card.get("entities", [])):
            if isinstance(row, Mapping):
                here = f"{where}.entities[{index}]"
                if "type" in row:
                    problems.append(f"{here}: row type `{row['type']}` is not allowed")
                    continue
                problems.extend(_check_options("row", here, row, ALLOWED_ROW_OPTIONS))
    return problems


def check_dashboard(dashboard: Mapping[str, Any]) -> list[str]:
    """Everything in a dashboard that is not a built-in card, feature, badge or option.

    Returns one message per problem, so an empty list means the dashboard passes.
    """
    problems: list[str] = []
    unknown = set(dashboard) - {"title", "views"}
    problems.extend(f"dashboard: option `{key}` is not allowed" for key in sorted(unknown))
    for v_index, view in enumerate(dashboard.get("views", [])):
        v_where = f"views[{v_index}]"
        problems.extend(_check_options("view", v_where, view, ALLOWED_VIEW_OPTIONS))
        if view.get("type") != "sections":
            problems.append(f"{v_where}: view type `{view.get('type')}` is not allowed")
        for s_index, section in enumerate(view.get("sections", [])):
            s_where = f"{v_where}.sections[{s_index}]"
            problems.extend(_check_options("section", s_where, section, ALLOWED_SECTION_OPTIONS))
            for c_index, card in enumerate(section.get("cards", [])):
                problems.extend(_check_card(f"{s_where}.cards[{c_index}]", card))
    return problems


# ---------------------------------------------------------------------------------------------
# Writing YAML
# ---------------------------------------------------------------------------------------------


class _Dumper(yaml.SafeDumper):
    """Block style, no aliases, multi-line text as literal blocks."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _represent_str(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _represent_str)


def render(dashboard: Mapping[str, Any]) -> str:
    """The dashboard as the text of ``dashboards/heating.yaml``."""
    body = yaml.dump(
        dashboard,
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        indent=2,
        width=10_000,
    )
    return HEADER + body


def render_file(source: Path) -> str:
    """Read a ``heating.yaml`` and return the dashboard text."""
    return render(build_dashboard(load_home(source)))


def _write_atomically(target: Path, text: str) -> None:
    """Replace ``target`` in one step, so Home Assistant never reads half a file."""
    target.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=target.parent, prefix=f".{target.name}.")
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as stream:
            stream.write(text)
        Path(temporary).chmod(0o644)
        Path(temporary).replace(target)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point; returns the exit status."""
    parser = argparse.ArgumentParser(
        description="Generate the heating dashboard from a heating.yaml.",
    )
    parser.add_argument("source", type=Path, help="the heating.yaml to read")
    parser.add_argument(
        "output", type=Path, help="the dashboard file to write; `-` writes to standard output"
    )
    args = parser.parse_args(argv)
    try:
        text = render_file(cast(Path, args.source))
        if str(args.output) == "-":
            sys.stdout.write(text)
        else:
            _write_atomically(args.output, text)
    except DashboardError as err:
        sys.stderr.write(f"render_dashboard: {err}\n")
        return 1
    except OSError as err:
        sys.stderr.write(f"render_dashboard: cannot write {args.output}: {err}\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
