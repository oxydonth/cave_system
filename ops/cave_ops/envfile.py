"""The ``.env`` file: the variable table of concept section 4.2, parsing and rendering.

``VARIABLES`` is the single list of variables. ``init`` renders ``.env`` from it, and
``.env.example`` is rendered from it too (a test fails when the checked-in file drifts; regenerate
it with ``PYTHONPATH=ops python3 -m cave_ops.envfile > .env.example``).
"""

