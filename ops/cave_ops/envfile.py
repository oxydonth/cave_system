def parse_env(text: str) -> dict[str, str]:
    """Parse ``KEY=value`` lines. Comments and blank lines are skipped; quotes are removed."""
    values: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export ") :]
        key, _, value = line.partition("=")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key.strip()] = value
    return values


def load_env(path: Path) -> dict[str, str]:
    """The variables in ``path``; an empty mapping when the file does not exist."""
    try:
        return parse_env(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}


def render(values: Mapping[str, str], variables: Iterable[Variable] = VARIABLES) -> str:
    """Render ``variables`` with their documentation, taking each value from ``values``."""
    blocks = []
    for var in variables:
        doc = "".join(f"# {line}\n" for line in var.doc.splitlines())
        blocks.append(f"{doc}{var.name}={values.get(var.name, var.default)}\n")
    return "\n".join(blocks)


def render_example() -> str:
    """The text of ``.env.example``."""
    return EXAMPLE_HEADER + "\n" + render({})


def fresh_values(
    data_dir: Path,
    *,
    generate: Callable[[], str] = generate_secret,
    existing: Mapping[str, str] | None = None,
    names: Iterable[str] = NAMES,
) -> dict[str, str]:
    """Defaults and generated secrets for the variables in ``names`` that ``existing`` lacks."""
    wanted = set(names)
    values: dict[str, str] = {}
    for var in VARIABLES:
        if var.name not in wanted or (existing is not None and var.name in existing):
            continue
        if var.name == "CAVE_DATA":
            values[var.name] = str(data_dir)
        elif var.generated:
            values[var.name] = generate()
        else:
            values[var.name] = var.default
    return values


def write_private(path: Path, text: str) -> None:
    """Create ``path`` with mode 0600, failing if it exists."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)


